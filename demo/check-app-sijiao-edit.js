// APP_URL=http://localhost:5173 CHROMIUM_PATH=/path/to/chromium bun demo/check-app-sijiao-edit.js
import { chromium } from 'playwright-core'
import { strict as assert } from 'node:assert'

const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH })
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 } })
  await page.goto(new URL('/sijiao', process.env.APP_URL ?? 'http://localhost:5173').href)
  const input = page.locator('.sijiao .code-input')
  const options = page.locator('.sijiao [role="option"]')
  const value = async (expected, message) => {
    assert.equal(await input.inputValue(), expected, message)
    assert.equal(new URL(page.url()).searchParams.get('q') ?? '', expected, 'URL tracks the code')
  }
  const select = (start, end = start) => input.evaluate((el, [a, b]) => el.setSelectionRange(a, b), [start, end])
  const selection = async (start, end = start) => assert.deepEqual(await input.evaluate(el => [el.selectionStart, el.selectionEnd]), [start, end])

  await input.fill('1234')
  await select(1)
  await input.press('9')
  await value('19234', 'digit inserts at the caret')
  await selection(2)
  await input.fill('1234')
  await select(1, 3)
  await input.press('9')
  await value('194', 'digit replaces the selection')
  await selection(2)
  await input.fill('1234')
  await select(2)
  await input.press('Backspace')
  await value('134', 'Backspace deletes before the caret')
  await selection(1)
  await input.fill('1234')
  await select(1, 3)
  await input.press('Backspace')
  await value('14', 'Backspace deletes the selection')
  await input.fill('1234')
  await select(1, 3)
  await input.press('Delete')
  await value('14', 'Delete deletes the selection')
  await input.fill('1234')
  await input.press('Home')
  await input.press('ArrowRight')
  await selection(1)
  await input.press('Shift+ArrowRight')
  await selection(1, 2)
  await input.press('8')
  await value('1834', 'arrow selection can be replaced')
  await input.press('End')
  await input.press('ArrowLeft')
  await selection(3)
  await input.press('Control+A')
  await input.press('6')
  await value('6', 'select-all can be replaced')
  await input.fill('123456')
  await select(1, 3)
  await input.press('8')
  await value('18456', 'replacement works at the six-digit limit')
  await input.fill('123456')
  await select(1)
  await input.press('9')
  await value('123456', 'inserting into a full code retains the suffix')
  await selection(1)
  await page.context().grantPermissions(['clipboard-read', 'clipboard-write'])
  await page.evaluate(() => navigator.clipboard.writeText('789'))
  await input.press('Control+V')
  await value('123456', 'pasting into a full code retains the suffix')
  await input.fill('12345')
  await select(1)
  await input.press('Control+V')
  await value('172345', 'a long paste fills the available space without losing the suffix')
  await input.fill('123456')
  await select(1, 3)
  await input.press('Control+V')
  await value('178456', 'pasting over a selection preserves the suffix at the limit')
  await input.fill('123456')
  await input.press('End')
  await input.press('7')
  await value('123456', 'input remains limited to six digits')
  await input.fill('1a2b345678')
  await value('123456', 'non-digits and excess input are filtered')
  await input.fill('1234')
  await select(1, 3)
  await page.context().grantPermissions(['clipboard-read', 'clipboard-write'])
  await page.evaluate(() => navigator.clipboard.writeText('a98b'))
  await input.press('Control+V')
  await value('1984', 'pasted text replaces the selection and is filtered')
  await selection(3)
  await input.fill('1234')
  await input.press('End')
  await input.press('Control+Backspace')
  await value('', 'modified Backspace retains native word deletion')
  await input.fill('1')
  const composingPrevented = await input.evaluate(el => !el.dispatchEvent(new KeyboardEvent('keydown', { key: 'Enter', bubbles: true, cancelable: true, isComposing: true })))
  assert.equal(composingPrevented, false, 'composition Enter is not intercepted')
  await value('1', 'composition Enter does not commit a candidate')
  await input.press('Escape')
  await value('', 'Escape clears the code')

  await page.locator('.sijiao .digit-key').filter({ hasText: '1' }).click()
  await value('1', 'on-screen digit appends')
  await options.nth(1).waitFor()
  await input.focus()
  await input.press('ArrowDown')
  assert.equal(await options.nth(1).getAttribute('aria-selected'), 'true', 'Down selects the next candidate')
  await input.press('ArrowUp')
  assert.equal(await options.nth(0).getAttribute('aria-selected'), 'true', 'Up selects the previous candidate')
  const modifiedPrevented = await input.evaluate(el => ['ArrowUp', 'ArrowDown', 'PageUp', 'PageDown'].map(key => !el.dispatchEvent(new KeyboardEvent('keydown', { key, shiftKey: true, bubbles: true, cancelable: true }))))
  assert.deepEqual(modifiedPrevented, [false, false, false, false], 'shifted navigation remains native')
  const altPrevented = await input.evaluate(el => !el.dispatchEvent(new KeyboardEvent('keydown', { key: 'ArrowLeft', altKey: true, bubbles: true, cancelable: true })))
  assert.equal(altPrevented, false, 'Alt+Left remains native')
  const pager = page.locator('.sijiao .ui-pager span')
  assert.equal(await pager.count(), 1)
  const firstPage = await pager.textContent()
  await input.press('PageDown')
  assert.notEqual(await pager.textContent(), firstPage, 'PageDown changes candidate page')
  await input.press('PageUp')
  assert.equal(await pager.textContent(), firstPage, 'PageUp returns to previous candidate page')
  await page.locator('.sijiao .digit-key').filter({ hasText: '2' }).click()
  await value('12', 'on-screen digit inserts at the caret')
  assert.equal(await input.evaluate(el => document.activeElement === el), true, 'desktop pad returns focus to the input')
  await page.locator('.sijiao .pad button[data-wide]').click()
  await value('1', 'on-screen Backspace deletes before the caret')
  assert.equal(await input.evaluate(el => document.activeElement === el), true, 'desktop Backspace returns focus to the input')
  await input.focus()
  await input.press('Space')
  await value('', 'Space commits a candidate')
  await input.fill('1')
  await options.first().waitFor()
  await input.press('Enter')
  await value('', 'Enter commits a candidate')
  await page.locator('.sijiao .digit-key').filter({ hasText: '1' }).click()
  await options.first().waitFor()
  await page.locator('.sijiao .pad button[data-space]').click()
  await value('', 'on-screen Space commits a candidate')
  if (process.env.SCREENSHOT_PATH) await page.screenshot({ path: process.env.SCREENSHOT_PATH })

  const mobile = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true })
  try {
    const phone = await mobile.newPage()
    await phone.goto(new URL('/sijiao', process.env.APP_URL ?? 'http://localhost:5173').href)
    const field = phone.locator('.sijiao .code-input')
    const digit = phone.locator('.sijiao .digit-key').filter({ hasText: '9' })
    const back = phone.locator('.sijiao .pad button[data-wide]')
    const choose = (start, end = start) => field.evaluate((el, [a, b]) => el.setSelectionRange(a, b), [start, end])
    const check = async (expected, caret) => {
      assert.equal(await field.inputValue(), expected)
      assert.equal(new URL(phone.url()).searchParams.get('q') ?? '', expected)
      assert.deepEqual(await field.evaluate(el => [el.selectionStart, el.selectionEnd]), [caret, caret])
      assert.equal(await field.evaluate(el => document.activeElement === el), true, 'touch pad keeps the caret visible')
    }
    assert.equal(await field.getAttribute('inputmode'), 'none', 'coarse pointer requests no system keyboard')
    await field.fill('1234')
    await choose(1)
    await field.evaluate(el => el.blur())
    await digit.tap()
    await check('19234', 2)
    await field.fill('1234')
    await choose(1, 3)
    await digit.tap()
    await check('194', 2)
    await field.fill('1234')
    await choose(2)
    await back.tap()
    await check('134', 1)
    await field.fill('1234')
    await choose(1, 3)
    await back.tap()
    await check('14', 1)
    await field.fill('123456')
    await choose(1)
    await digit.tap()
    await check('123456', 1)
    await field.fill('123456')
    await choose(1, 3)
    await digit.tap()
    await check('19456', 2)
    await field.fill('12')
    await digit.focus()
    await phone.keyboard.press('Enter')
    assert.equal(await field.inputValue(), '129', 'keyboard activation still operates a pad key')
    assert.equal(await digit.evaluate(el => document.activeElement === el), true, 'keyboard activation keeps focus on the key')
  } finally {
    await mobile.close()
  }
  console.log('PASS four-corner editing and shortcuts')
} finally {
  await browser.close()
}
